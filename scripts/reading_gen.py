#!/usr/bin/env python3
"""Deterministic reading generator. Same chart.json -> byte-identical reading.md."""
import argparse
import json
from pathlib import Path

SIGNS = "Aries Taurus Gemini Cancer Leo Virgo Libra Scorpio Sagittarius Capricorn Aquarius Pisces".split()
HOUSES = ["self/identity", "family/wealth/speech", "courage/siblings/effort", "home/roots/mother",
          "creativity/intelligence/children", "health/service/opponents", "partnership/others",
          "longevity/shared-resources/hidden", "fortune/dharma/travel", "career/status",
          "gains/networks", "withdrawal/losses/foreign-residence"]

def fmt_deg(p):
    return f"{p['sign']} {p['degree_in_sign']:.2f}°"

def load(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chart", required=True)
    ap.add_argument("--request", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    chart = load(args.chart)
    req = load(args.request)
    vin = chart["vimshottari"]
    jy = chart["jyotisha"]
    we = chart["western"]
    cur = vin.get("current")

    lines = []
    lines.append(f"# Kundali Reading — {req.get('label', 'Private chart')}")
    lines.append("")
    lines.append("## 1. Purpose and data quality")
    lines.append("Deterministic reading generated by `scripts/reading_gen.py` from `chart.json`. Astrology is a symbolic/traditional practice; claims are not scientifically established predictions.")
    lines.append(f"- Birth: {req['birth']['date']} {req['birth']['time']} {req['birth']['timezone']}, {req['birth']['place']}")
    lines.append(f"- Coordinates: {req['birth']['latitude']}N, {req['birth']['longitude']}E ({req['birth'].get('coordinate_source', 'unspecified')})")
    lines.append(f"- Uncertainty: ±{req['birth'].get('uncertainty_minutes', 0)} min; generated {chart['provenance']['as_of_utc']}")
    lines.append("")

    lines.append("## 2. Calculation manifest")
    lines.append(f"- Engine: {chart['provenance']['engine']}; flags as recorded in chart.json")
    lines.append(f"- Ayanamsha (Lahiri): {jy['ayanamsha_degrees']:.4f}°")
    lines.append(f"- Western houses: {we['house_method']} (tropical, mean nodes); Jyotisha: whole-sign, mean nodes")
    lines.append(f"- Dasha year: {vin['year_days']} days; as_of: {chart['provenance']['as_of_utc']}")
    lines.append("")

    lines.append("## 3. Chart atlas and quick reference")
    lines.append("Diagrams: `charts.html` (generated by chart_engine.py).")
    lines.append("")

    lines.append("## 4. Core data tables (source: chart.json)")
    lines.append("| Body | Western (sign deg, H) | Jyotisha (sign deg, H) |")
    lines.append("|---|---|---|")
    for b in ["Sun", "Moon", "Mercury", "Venus", "Mars", "Jupiter", "Saturn", "Rahu", "Ketu"]:
        wp, jp = we["planets"][b], jy["planets"][b]
        lines.append(f"| {b} | {fmt_deg(wp)} H{wp['house']} | {fmt_deg(jp)} H{jp['house']} |")
    lines.append(f"| Ascendant | {fmt_deg(we['ascendant'])} | {fmt_deg(jy['ascendant'])} |")
    lines.append(f"| Nakshatra | — | {jy['moon_nakshatra']['name']} Pada {jy['moon_nakshatra']['pada']} (lord {jy['moon_nakshatra']['lord']}) |")
    lines.append("")

    lines.append("## 5. Western analysis")
    lines.append(f"- Ascendant {fmt_deg(we['ascendant'])}; MC {fmt_deg(we['midheaven'])}.")
    for b in ["Sun", "Moon", "Mercury", "Venus", "Mars", "Jupiter", "Saturn"]:
        wp = we["planets"][b]
        lines.append(f"- {b}: {fmt_deg(wp)}, house {wp['house']} ({HOUSES[wp['house']-1]}){' Rx' if wp['retrograde'] else ''}.")
    lines.append("- Aspects (orb ≤6°): " + "; ".join(f"{a['from']}–{a['to']} {a['aspect']} {a['orb']:.2f}°" for a in we["aspects"][:8] or ["none"]))
    lines.append("")

    lines.append("## 6. Jyotisha analysis")
    for h in range(1, 13):
        occupants = [b for b, p in jy["planets"].items() if p["house"] == h]
        desc = (", ".join(f"{b} {fmt_deg(jy['planets'][b])}" for b in occupants) or "empty; read via lordship/aspects")
        lines.append(f"- **Bhava {h} ({HOUSES[h-1]}):** {desc}.")
    lines.append(f"- D9 ASC: {fmt_deg(jy['D9']['ascendant'])}; D10 ASC: {fmt_deg(jy['D10']['ascendant'])}. See charts.html for placements.")
    lines.append("- Sign-level dignities only; degree-based strengths/combustion not assessed.")
    lines.append("")

    lines.append("## 7. Topic readings")
    lines.append("Cross-tradition themes (evidence from §4–§6): identity (Mercury placement), career (10th lord + 10th occupancy), wealth (2nd lord/occupancy), family/home (4th), creativity (5th), travel/meaning (9th). Detail follows the house paragraphs in §6.")
    lines.append("")

    lines.append("## 8. Timing")
    lines.append(f"- Birth lord {vin['birth_lord']}; balance {vin['birth_balance_years']:.2f} years.")
    lines.append("| Mahadasha | Ends (UT) |")
    lines.append("|---|---|")
    for m in vin["mahadashas"]:
        lines.append(f"| {m['lord']} | {m['end_utc'][:10]} |")
    if cur:
        lines.append(f"- Current: {cur['mahadasha']}–{cur['antardasha']} → {cur['end_utc'][:10]}")
    lines.append("")

    lines.append("## 9. Actionable reflection")
    lines.append("Practical inference only (not proof): track three placements that repeat across Western, Jyotisha, D9 and D10; test whether they describe lived patterns, then keep or discard. No medical, investment or irreversible-life prescriptions.")
    lines.append("")

    lines.append("## 10. Quality and sources")
    lines.append("- Warnings from chart.json: " + "; ".join(chart["warnings"]))
    lines.append("- Calculated: " + ", ".join(["D1", "D9", "D10", "aspects", "graha drishti", "tithi", "Vimshottari MD/AD", "transit snapshot"]))
    lines.append("- Not assessed: shadbala, ashtakavarga, combustion, degree strengths, other vargas, compatibility, exact-event search, full panchanga.")
    lines.append("")

    lines.append("## 11. Continuity")
    lines.append(f"Artifacts: chart.json, charts.html, calculation.md, reading.md. Deterministic output; regenerate after any setting change.")
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"written: {args.out}")

if __name__ == "__main__":
    main()
